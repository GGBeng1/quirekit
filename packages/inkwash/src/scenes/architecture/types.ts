/** 一座楼阁：世界坐标中的位置、远近、重檐数、笔触种子，以及尺寸与所坐台基的高度。 */
export interface Hall {
    /** 横向位置（世界单位，0 为宫城中轴）。 */
    x: number;
    /** 纵深位置（世界单位，越大越远）。 */
    z: number;
    /** 屋顶重数（1–3）。 */
    tiers: number;
    /** 笔触噪声种子。 */
    seed: number;
    /** 相对标准楼阁的尺寸倍数。 */
    size: number;
    /** 楼阁坐落的台基高度（世界单位，0 为地面）。 */
    lift: number;
}
