import { createSelectionGestureSession } from './session/controller';
import type { CreateQuireSelectionGestureOptions, QuireKitSelectionGestureProps, QuireSelectionGestureController } from './types';

/**
 * Binds optional surface long-press selection while yielding ordinary touch scrolling.
 * @param options - Explicit surface, recognition settings and semantic callbacks.
 * @returns Update and teardown lifecycle; no editor or menu ownership is acquired.
 */
export function createQuireSelectionGesture(options: CreateQuireSelectionGestureOptions): QuireSelectionGestureController {
  const target = options.target;
  const doc = target.ownerDocument;
  const win = doc.defaultView!;
  if (!win) throw new Error('Selection gestures require a document with a window.');
  const hadClass = target.classList.contains('qk-selection-gesture');
  target.classList.add('qk-selection-gesture');
  let props: QuireKitSelectionGestureProps = options;
  let destroyed = false;
  let suppressClick = false;
  const session = createSelectionGestureSession({
    delay: (callback, delay) => win.setTimeout(callback, delay), cancelDelay: id => win.clearTimeout(id),
    frame: callback => win.requestAnimationFrame(callback), cancelFrame: id => win.cancelAnimationFrame(id),
    onLongPressStart(detail) { suppressClick = true; options.onLongPressStart?.(detail); },
    onLongPress(detail) { listen(false); options.onLongPress?.(detail); },
    onSelectionStart: detail => options.onSelectionStart?.(detail),
    onSelectionChange: detail => options.onSelectionChange?.(detail),
    onSelectionComplete(detail) { listen(false); options.onSelectionComplete?.(detail); },
    onCancel(detail) { listen(false); options.onCancel?.(detail); }
  });
  /** @returns Whether scrolling belongs to an accepted hold or drag. */
  function accepted(): boolean { return session.phase() === 'pressed' || session.phase() === 'dragging'; }
  /** @param event - Claimed input. */
  function consume(event: Event): void { event.preventDefault(); event.stopPropagation(); }
  /** @param event - Initial surface input; native controls and nested owners keep their gestures. */
  function down(event: PointerEvent): void {
    suppressClick = false;
    if (destroyed || props.disabled || event.button !== 0 || !event.isPrimary || options.ignore?.(event)) return;
    const origin = event.composedPath().find(entry => entry instanceof win.Element) as Element | undefined;
    const control = origin?.closest('button, input, textarea, select, a[href], [role="button"], [contenteditable], .qk-selection-handles, .qk-selection-gesture');
    if (control && control !== target) return;
    const point = { x: event.clientX, y: event.clientY };
    session.begin({ pointerId: event.pointerId, pointerType: event.pointerType, origin: point, point }, props);
    if (session.current()) listen(true);
  }
  /** @param event - Raw pointer sample; waiting motion yields to native scrolling. */
  function move(event: PointerEvent): void {
    if (session.current()?.pointerId !== event.pointerId) return;
    if (accepted()) consume(event);
    session.move(event.pointerId, { x: event.clientX, y: event.clientY });
    if (!session.current()) listen(false);
  }
  /** @param event - Final point; pending ordinary taps remain available to the host. */
  function up(event: PointerEvent): void {
    if (session.current()?.pointerId !== event.pointerId) return;
    if (accepted()) consume(event);
    session.release(event.pointerId, { x: event.clientX, y: event.clientY });
    if (!session.current()) listen(false);
  }
  /** @param event - Native scroll cancellation or another interrupted pointer. */
  function cancelPointer(event: PointerEvent): void {
    if (session.current()?.pointerId !== event.pointerId) return;
    session.cancel('cancel');
    listen(false);
  }
  /** @param event - A second pointer yields the gesture to the browser. */
  function anotherPointer(event: PointerEvent): void {
    if (session.current()?.pointerId === event.pointerId) return;
    session.cancel('multitouch');
    listen(false);
  }
  /** @param event - Only an accepted hold may prevent the first native scroll movement. */
  function touchMove(event: TouchEvent): void { if (accepted() && event.cancelable) event.preventDefault(); }
  /** @param event - Native context menu generated by a claimed touch/pen hold. */
  function context(event: MouseEvent): void { if (session.current() || suppressClick) consume(event); }
  /** @param event - One compatibility click following a long press, never a new physical click. */
  function click(event: MouseEvent): void {
    if (suppressClick && event.detail !== 0) { suppressClick = false; consume(event); }
  }
  /** Cancels when the window loses input ownership. */
  function blur(): void { session.cancel('blur'); listen(false); }
  /** Cancels hidden pages to prevent delayed recognition after returning. */
  function visibility(): void { if (doc.hidden) blur(); }
  /** Cancels pre-hold scrolling; accepted host autoscroll remains supported. */
  function scroll(): void { if (session.phase() === 'pending') { session.cancel('scroll'); listen(false); } }
  /** @param event - Explicit keyboard cancellation. */
  function escape(event: KeyboardEvent): void {
    if (event.key !== 'Escape') return;
    if (accepted()) consume(event);
    session.cancel('escape');
    listen(false);
  }
  /** @param active - Candidate-scoped listeners, removed even when scrolling cancels silently. */
  function listen(active: boolean): void {
    const method = active ? 'addEventListener' : 'removeEventListener';
    win[method]('pointermove', move as EventListener, true);
    win[method]('pointerup', up as EventListener, true);
    win[method]('pointercancel', cancelPointer as EventListener, true);
    win[method]('pointerdown', anotherPointer as EventListener, true);
    win[method]('keydown', escape as EventListener, true);
    win[method]('scroll', scroll, true);
    win[method]('blur', blur);
    doc[method]('visibilitychange', visibility);
    target[method]('touchmove', touchMove as EventListener, { passive: false });
  }
  target.addEventListener('pointerdown', down);
  target.addEventListener('contextmenu', context);
  target.addEventListener('click', click, true);
  return {
    /** @param next - Recognition configuration; a live gesture keeps its original thresholds. */
    update(next) {
      if (destroyed) return;
      props = next;
      if (props.disabled) { session.cancel('disabled'); listen(false); }
    },
    /** Drops a gesture whose host document target is no longer valid. */
    cancel() { session.cancel('cancel'); listen(false); },
    /** Releases listeners, timeouts, frames and the class owned by this binding. */
    destroy() {
      if (destroyed) return;
      destroyed = true;
      session.cancel('destroy');
      listen(false);
      target.removeEventListener('pointerdown', down);
      target.removeEventListener('contextmenu', context);
      target.removeEventListener('click', click, true);
      if (!hadClass) target.classList.remove('qk-selection-gesture');
    }
  };
}
