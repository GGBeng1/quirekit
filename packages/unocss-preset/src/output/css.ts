/**
 * Generates semantic-token CSS for the built-in QuireKit theme profiles.
 *
 * @returns Complete CSS generated from the same preset used by applications.
 */
export async function generateQuireKitCss(): Promise<string> {
  const generator = await createGenerator(defineQuireKitUnoConfig());
  const result = await generator.generate([
    ...quireKitUnoUtilityCatalog,
    ...accordionRecipeCatalog,
    ...actionSheetRecipeCatalog,
    ...badgeRecipeCatalog,
    ...dateInputRecipeCatalog,
    ...timeInputRecipeCatalog,
    ...calendarRecipeCatalog,
      ...datePickerRecipeCatalog,
      ...timePickerRecipeCatalog,
      ...timeRangePickerRecipeCatalog,
      ...dateTimePickerRecipeCatalog,
      ...dateTimeRangePickerRecipeCatalog,
      ...cardRecipeCatalog,
      ...floatingPanelRecipeCatalog,
      ...separatorRecipeCatalog,
      ...codeBlockRecipeCatalog,
      ...proseRecipeCatalog,
      ...descriptionsRecipeCatalog,
      ...hierarchyPickerRecipeCatalog,
      ...hoverCardRecipeCatalog,
      ...popconfirmRecipeCatalog,
      ...imagePreviewRecipeCatalog,
      ...timelineRecipeCatalog,
      ...chatRecipeCatalog,
      ...sourceRecipeCatalog,
      ...shimmerRecipeCatalog,
      ...htmlSandboxRecipeCatalog,
      ...attachmentRecipeCatalog,
      ...fileIconRecipeCatalog,
      ...resultRecipeCatalog,
      ...controlGroupRecipeCatalog,
      ...pinInputRecipeCatalog,
      ...statisticRecipeCatalog,
      ...ratingRecipeCatalog,
      ...qrCodeRecipeCatalog,
      ...carouselRecipeCatalog,
      ...imageCropperRecipeCatalog,
      ...transferRecipeCatalog,
      ...anchorRecipeCatalog,
      ...spaceRecipeCatalog,
      ...breadcrumbRecipeCatalog,
      ...navigationMenuRecipeCatalog,
      ...commandPaletteRecipeCatalog,
      ...stepsRecipeCatalog,
      ...dateRangePickerRecipeCatalog,
      ...tagRecipeCatalog,
    ...skeletonRecipeCatalog,
    ...kbdRecipeCatalog,
    ...checkboxGroupRecipeCatalog,
    ...toggleGroupRecipeCatalog,
    ...tableRecipeCatalog,
    ...buttonRecipeCatalog,
    ...checkboxRecipeCatalog,
    ...collapsibleRecipeCatalog,
    ...comboboxRecipeCatalog,
    ...colorPickerRecipeCatalog,
    ...dialogRecipeCatalog,
    ...drawerRecipeCatalog,
    ...fieldRecipeCatalog,
    ...iconRecipeCatalog,
    ...inputRecipeCatalog,
    ...inputNumberRecipeCatalog,
    ...inspectorRecipeCatalog,
    ...menuRecipeCatalog,
    ...popoverRecipeCatalog,
    ...radioGroupRecipeCatalog,
    ...segmentedRecipeCatalog,
    ...sliderRecipeCatalog,
      ...mediaPlayerRecipeCatalog,
    ...switchRecipeCatalog,
    ...tabsRecipeCatalog,
    ...textareaRecipeCatalog,
    ...tooltipRecipeCatalog,
    ...toolbarRecipeCatalog
  ].join(" "), {
    preflights: true
  });
  return `${result.css.trim()}\n`;
}
