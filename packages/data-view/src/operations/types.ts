import type { DataField, DataRecord, DataValue } from "../model/types";

/** One atomic dataset operation identified by stable IDs. */
export type DataOperation =
  | { readonly type: "set-cell"; readonly recordId: string; readonly fieldId: string; readonly value: DataValue }
  | { readonly type: "insert-record"; readonly record: DataRecord }
  | { readonly type: "delete-record"; readonly recordId: string }
  | { readonly type: "add-field"; readonly field: DataField; readonly defaultValue: DataValue }
  | { readonly type: "replace-field"; readonly field: DataField; readonly values?: Readonly<Record<string, DataValue>> }
  | { readonly type: "delete-field"; readonly fieldId: string; readonly replacementGroupFieldId?: string };

/** Embed-local projection changes published with the dataset mutation. */
export interface DataViewMutationOptions {
  /** Appends newly added fields to this view only; omitted calls retain existing visibility. */
  readonly showAddedFieldsIn?: string;
}

/** Equality-only optimistic commit boundary. */
export interface DataMutationVersion {
  /** Revision read when the operation was prepared. */
  readonly baseRevision: string;
  /** New opaque version generated by the authority. */
  readonly revision: string;
}
