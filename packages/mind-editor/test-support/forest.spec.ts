import { toggleMindPreviewTheme } from "./preferences/testing";
import { expect, test } from "@playwright/test";

test("public toolbar creates an editable free tree and preserves it across reload and themes", async ({ page }, info) => {
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/"); await expect(page.locator(".smm-node")).toHaveCount(14);
  await page.getByRole("button", { name: "插入", exact: true }).click(); await page.getByRole("menuitem", { name: "自由主题", exact: true }).click();
  const free = page.locator(".smm-node").filter({ hasText: /^自由主题$/ });
  await expect(free).toBeVisible(); await free.dblclick();
  await page.locator('[contenteditable="true"]').fill("待整理的灵感"); await page.keyboard.press("Enter");
  await page.getByRole("button", { name: "新增子主题", exact: true }).click();
  await expect(page.locator(".smm-node")).toHaveCount(16);
  await page.getByRole("button", { name: "保存到本机", exact: true }).click();
  await expect(page.getByRole("button", { name: "已保存到本机", exact: true })).toBeVisible();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("quirekit-mind-editor-preview-v1")!));
  expect(saved.version).toBe(2); expect(saved.floatingTopics[0].root.text).toBe("待整理的灵感");
  expect(saved.floatingTopics[0].root.children).toHaveLength(1);
  await page.reload(); await expect(page.locator(".smm-node")).toHaveCount(16);
  await expect(page.locator(".smm-node").filter({ hasText: /^待整理的灵感$/ })).toBeVisible();
  await page.getByRole("button", { name: "适应画布", exact: true }).click();
  await page.screenshot({ path: info.outputPath("free-topic-light.png") });
  await toggleMindPreviewTheme(page);
  await expect(page.locator(".smm-node")).toHaveCount(16);
  await page.screenshot({ path: info.outputPath("free-topic-dark.png") });
  expect(errors).toEqual([]);
});

test("blank double-click creates at the pointer and full selection pans together before batch deletion", async ({ page }, info) => {
  await page.goto("/"); await expect(page.locator(".smm-node")).toHaveCount(14);
  const canvas = (await page.locator("[data-quirekit-mind-map]").boundingBox())!;
  await page.mouse.dblclick(canvas.x + 60, canvas.y + canvas.height - 100);
  await expect(page.locator(".smm-node").filter({ hasText: /^自由主题$/ })).toBeVisible();
  await page.getByRole("button", { name: "适应画布", exact: true }).click();
  await page.mouse.click(canvas.x + 12, canvas.y + 12);
  await page.mouse.down({ clickCount: 2 });
  await page.mouse.move(canvas.x + canvas.width - 12, canvas.y + canvas.height - 12, { steps: 8 });
  await expect(page.locator(".qk-mind-editor__hint")).toContainText("已选 15 个主题");
  await page.screenshot({ path: info.outputPath("marquee-blue.png") });
  await page.mouse.up({ clickCount: 2 });
  await expect(page.locator(".qk-mind-editor__hint")).toContainText("已选 15 个主题");
  await expect(page.locator(".smm-node")).toHaveCount(15);
  await expect(page.locator("[data-mind-gesture]")).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("quick-marquee-selection.png") });
  const root = page.locator(".smm-node").filter({ hasText: /^时间管理$/ }).locator("text");
  const rootBefore = (await root.boundingBox())!;
  const branch = (await page.locator(".smm-node").filter({ hasText: /^下周安排$/ }).locator("text").boundingBox())!;
  await page.mouse.move(branch.x + branch.width / 2, branch.y + branch.height / 2); await page.mouse.down();
  await page.mouse.move(branch.x + branch.width / 2 + 45, branch.y + branch.height / 2 - 25, { steps: 6 });
  expect((await root.boundingBox())!.x - rootBefore.x).toBeCloseTo(45, 0);
  expect((await root.boundingBox())!.y - rootBefore.y).toBeCloseTo(-25, 0);
  await expect(page.locator("[data-mind-gesture]")).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("whole-selection-pan.png") });
  await page.mouse.up();
  await expect(page.locator(".qk-mind-editor__hint")).toContainText("已选 15 个主题");
  await page.getByRole("button", { name: "编辑", exact: true }).click();
  await expect(page.getByRole("menuitem", { name: /^编辑文字/ })).toHaveAttribute("aria-disabled", "true");
  await page.getByRole("menuitem", { name: /^删除主题/ }).click();
  await expect(page.locator(".smm-node")).toHaveCount(1);
  await page.getByRole("button", { name: "撤销", exact: true }).click();
  await expect(page.locator(".smm-node")).toHaveCount(15);
});
