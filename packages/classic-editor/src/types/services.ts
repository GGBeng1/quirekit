import type { ClassicEditorText } from "./base";
import type { ClassicEditorRenderContext } from "./context";

/** Context supplied to import/export services. */
export interface ClassicEditorServiceContext extends ClassicEditorRenderContext {}

/** Optional cancellation owned by the host that opens a document. */
export interface ClassicEditorImportOptions {
  /** Cancels preparation and rejects any later commit from this operation. */
  readonly signal?: AbortSignal | undefined;
}

/** Instance-owned final write boundary supplied only to document import services. */
export interface ClassicEditorImportContext extends ClassicEditorServiceContext {
  /** Cancels when the operation, target session or host request becomes invalid. */
  readonly signal: AbortSignal;
  /**
   * Validates the original target and executes one synchronous document command.
   * @param write - Synchronous typed-command call; return true only after acceptance.
   */
  commit(write: () => boolean): void;
}

/** User-selected input artifact passed to one document import service. */
export interface ClassicEditorImportArtifact {
  /** Complete source bytes or decoded text. */
  readonly data: Uint8Array | string;
  /** Original local file name when selected in the browser. */
  readonly fileName: string;
  /** Browser-provided MIME type, when available. */
  readonly mimeType?: string | undefined;
}

/** Downloadable artifact returned by one document export service. */
export interface ClassicEditorExportArtifact {
  /** Complete generated bytes or text. */
  readonly data: Uint8Array | string;
  /** Suggested download file name including extension. */
  readonly fileName: string;
  /** Artifact MIME type. */
  readonly mimeType: string;
}

/** File-format metadata used by browser chrome and external consumers. */
export interface ClassicEditorDocumentFormat {
  /** Stable format identifier such as `docx` or `json`. */
  readonly id: string;
  /** File extensions including the leading dot. */
  readonly extensions: readonly string[];
  /** Accepted MIME types. */
  readonly mimeTypes: readonly string[];
}

/** Named import/export service contributed to the product registry. */
export interface ClassicEditorImportExportService {
  /** Stable service id. */
  readonly id: string;
  /** Human-readable service label. */
  readonly label: ClassicEditorText;
  /** File-format capability exposed by this service. */
  readonly format: ClassicEditorDocumentFormat;
  /**
   * Imports external input into the current canonical Core document.
   *
   * @param context - Mounted product service context.
   * @param input - User-selected or programmatic file artifact.
   * @returns Optional asynchronous completion.
   */
  import?(
    context: ClassicEditorImportContext,
    input: ClassicEditorImportArtifact
  ): void | Promise<void>;
  /**
   * Exports the current canonical Core document.
   *
   * @param context - Mounted product service context.
   * @returns Downloadable artifact, optionally asynchronous.
   */
  export?(
    context: ClassicEditorServiceContext
  ): ClassicEditorExportArtifact | Promise<ClassicEditorExportArtifact>;
}
